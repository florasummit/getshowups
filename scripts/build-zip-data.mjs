// Builds server/zip-data.js: the set of real US ZIP Code Tabulation Areas as a bitset (one bit per 5-digit code,
// 12,500 bytes, base64). Source: U.S. Census Bureau Gazetteer Files, ZCTAs (public domain), e.g.
//   https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2024_Gazetteer/2024_Gaz_zcta_national.zip
// Usage: node scripts/build-zip-data.mjs <path to the unzipped *_Gaz_zcta_national.txt> <vintage, e.g. 2024>
// ZCTAs cover residential/business delivery areas; PO-box-only and single-organization ZIPs are not in it, so a code
// missing from this set is "unknown" (ask to double-check), never proof that it does not exist (server/zipcode.js).
import { readFileSync, writeFileSync } from 'node:fs'

const [file, vintage] = process.argv.slice(2)
if (!file || !/^\d{4}$/.test(vintage || '')) {
  console.error('usage: node scripts/build-zip-data.mjs <Gaz_zcta_national.txt> <vintage>')
  process.exit(1)
}
const bits = new Uint8Array(12_500)
let count = 0
for (const line of readFileSync(file, 'utf8').split('\n').slice(1)) {
  const zip = line.slice(0, 5)
  if (!/^\d{5}$/.test(zip)) continue
  const n = Number(zip)
  if (!(bits[n >> 3] & (1 << (n & 7)))) count++
  bits[n >> 3] |= 1 << (n & 7)
}
if (count < 30_000) throw new Error(`only ${count} ZCTAs read: wrong file?`)
const b64 = Buffer.from(bits).toString('base64')
writeFileSync(
  new URL('../server/zip-data.js', import.meta.url),
  `// GENERATED by scripts/build-zip-data.mjs — do not edit. U.S. Census Bureau ${vintage} Gazetteer, ZIP Code Tabulation\n` +
    `// Areas (public domain): ${count} codes, one bit per 5-digit code.\n` +
    `export const ZCTA_VINTAGE = ${vintage}\nexport const ZCTA_COUNT = ${count}\nexport const ZCTA_BITS = '${b64}'\n`,
)
console.log(`server/zip-data.js: ${count} ZCTAs (${vintage}), ${b64.length} base64 chars`)
