const OPTS = (id, page = '') => ({
  canonical: `https://getshowups.com/p/${id}`,
  bookUrl: `https://getshowups.com/book/${id}`,
  privacyUrl: 'https://getshowups.com/privacy',
  year: 2026,
  page,
  pageBase: `/p/${id}`,
  form: { action: `https://getshowups.com/api/site-form/${id}`, token: 'FORM_TOKEN', state: null, attribution: {} },
})

function fixture(name) {
  const file = new URL(`${name}.json`, DIR)
  if (existsSync(file)) return JSON.parse(readFileSync(file, 'utf8'))
  assert.ok(UPDATE, `missing content fixture ${name}.json (run with UPDATE_RENDER_GOLDEN=1 once)`)
  const f = CASES[name]()
  const id = `golden-${name}`
  const out = { biz: { id, phone: '(843) 555-0100', cities: ['Charleston'], hours: { dayStart: 540, dayEnd: 1020, workdays: [1, 2, 3, 4, 5] }, offerSms: false, smsTermsUrl: `https://getshowups.com/sms-terms/${id}`, ...f.biz }, content: f.content }
  mkdirSync(DIR, { recursive: true })
  writeFileSync(file, `${JSON.stringify(out, null, 2)}\n`)
  return out
}

for (const name of Object.keys(CASES)) {
  test(`published site renders exactly as before: ${name}`, () => {
    const { biz, content } = fixture(name)
    const pages = content.site ? content.site.pages.map((p) => p.slug) : ['']
    for (const page of pages) {
      const html = renderSite(biz, content, OPTS(biz.id, page))
      const file = new URL(`${name}${page ? `.${page}` : ''}.html`, DIR)
      if (UPDATE) writeFileSync(file, html)
      assert.ok(existsSync(file), `missing golden ${name}${page ? `.${page}` : ''}.html`)
      const golden = readFileSync(file, 'utf8')
      if (html !== golden) {
        const at = [...html].findIndex((ch, i) => ch !== golden[i])
        assert.fail(`Rendered HTML for published content "${name}"${page ? ` page "${page}"` : ''} changed at char ${at}:\n  was: ${JSON.stringify(golden.slice(Math.max(0, at - 60), at + 80))}\n  now: ${JSON.stringify(html.slice(Math.max(0, at - 60), at + 80))}\nThis changes live customer websites. If intended, regenerate (UPDATE_RENDER_GOLDEN=1) and call it out in the PR.`)
      }
    }
  })
}

test('render goldens cover every content system, both appointment modes and a multi-page site', () => {
  const all = Object.keys(CASES).map((n) => fixture(n))
  assert.ok(all.some((f) => !f.content.site && !f.content.design), 'legacy content')
  assert.ok(all.some((f) => f.content.design && !f.content.site), 'content.design')
  assert.ok(all.some((f) => f.content.site), 'content.site v2')
  assert.ok(all.some((f) => (f.content.site?.pages || []).length > 1), 'multi-page')
  assert.deepEqual(new Set(all.map((f) => f.biz.appointmentMode)), new Set(['at_customer', 'at_business']))
})

// One service catalog (server/website-catalog.js, WEB-14): a live site whose services equal Settings → Services renders
// byte-identical HTML with the catalog applied (also when the catalog has no descriptions, as setup creates it).
test('published sites whose services equal the catalog render exactly as before with the catalog applied', () => {
  for (const name of Object.keys(CASES)) {
    const { biz, content } = fixture(name)
    const catalog = readServices((content.services || []).map((s) => ({ name: s.name, price: s.price, description: s.description })))
    const bare = readServices((content.services || []).map((s) => ({ name: s.name, price: s.price })))
    for (const page of content.site ? content.site.pages.map((p) => p.slug) : ['']) {
      const golden = renderSite(biz, content, OPTS(biz.id, page))
      assert.equal(renderSite({ ...biz, catalog }, content, OPTS(biz.id, page)), golden, `${name} ${page}`)
      assert.equal(renderSite({ ...biz, catalog: bare }, content, OPTS(biz.id, page)), golden, `${name} ${page} (no descriptions)`)
    }
  }
})
