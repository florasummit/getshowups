// Admin Console → Voice providers (/admin/voice-providers) in a real browser against the real Functions on local
// workerd, Retell faked at the network edge: the FIRST platform admin (a member of no business) picks a business,
// sees its active provider, readiness, history and blockers, and runs Review → Activate (business id typed back) →
// Rollback on an admin-marked test business seeded on OpenAI (not configured here) with a finished Retell test session.
// A live business without evidence is blocked by the checklist; owners get neither the page nor the API. Desktop only.
import { test, expect } from './test.js'
import { fixtures } from '../../playwright.config.js'
import { useSession } from './helpers.js'

test.describe.configure({ mode: 'serial', timeout: 90_000 })
const noSideScroll = async (page) => expect(await page.evaluate(() => document.documentElement.scrollWidth - Math.min(window.innerWidth, screen.width))).toBeLessThanOrEqual(0)

test('admin (member of nothing): picks a live business, sees honest states and blockers, the checklist blocks an unverified switch, nothing changes; owners are refused', async ({ page, context }) => {
  await useSession(context, fixtures.E2E_ADMIN_SESSION_TOKEN)
  await page.goto('/admin')
  await page.getByRole('navigation', { name: 'Admin' }).getByRole('link', { name: 'Voice providers' }).click()
  await expect(page).toHaveURL(/\/admin\/voice-providers$/)
  await expect(page.getByRole('heading', { level: 1, name: 'Voice providers' })).toBeVisible()
  const list = await (await page.request.get('/api/platform/voice-provider')).json()
  const voice = list.businesses.find((b) => b.id === fixtures.E2E_VOICE_CUSTOMER)
  expect([voice.name, voice.test, voice.receptionist, voice.provider]).toEqual(['Voice Pools', false, true, 'retell'])
  expect(JSON.stringify(list)).not.toMatch(/@|sk-|Bearer/)
  await page.getByRole('combobox', { name: 'Business' }).selectOption(fixtures.E2E_VOICE_CUSTOMER)
  await expect(page).toHaveURL(new RegExp(`customer=${fixtures.E2E_VOICE_CUSTOMER}$`))
  const selected = page.locator('[data-vp-selected]')
  await expect(selected).toHaveAttribute('data-vp-selected', fixtures.E2E_VOICE_CUSTOMER)
  await expect(selected).toContainText('Voice Pools')
  await expect(selected).toContainText('Live business: real customers')
  await expect(selected).toContainText('Retell')
  await expect(selected).toContainText('Phone routing')
  await expect(page.locator('[data-vp-state="retell"]')).toContainText('Active for customers')
  await expect(page.locator('[data-vp-state="openai"]')).toContainText('Not configured')
  await expect(page.locator('[data-vp-state="elevenlabs"]')).toContainText('Not configured')
  await expect(page.getByRole('region', { name: 'Test history' })).toContainText('No voice sessions yet.')
  const control = page.locator('[data-provider-control]')
  await expect(control).toHaveCount(1)
  await expect(control.getByRole('row', { name: /Retell/ })).toContainText('Active for customers')
  await control.getByRole('combobox', { name: 'Provider to switch to' }).selectOption('elevenlabs')
  await control.getByRole('checkbox').check()
  await expect(control.locator('[data-test-now]')).toHaveCount(0, 'not a test business: no Test now link')
  await control.getByRole('button', { name: 'Review checklist' }).click()
  const check = control.getByLabel('Switching checklist')
  await expect(check).toContainText('is not configured')
  await expect(check).toContainText('Not verified for this business yet')
  await expect(control.getByRole('button', { name: 'Activate…' })).toBeDisabled()
  await expect(control.locator('[data-confirm-business]')).toHaveCount(0)
  await noSideScroll(page)
  // Server-side: a switch without the typed id is refused before anything else; with it, the checklist blocks; the
  // business stays on Retell; the owner's session cannot use the console route at all.
  const origin = new URL(page.url()).origin
  const view = await (await page.request.get(`/api/platform/voice-provider?customer=${fixtures.E2E_VOICE_CUSTOMER}`)).json()
  const noId = await page.request.post('/api/platform/voice-provider', { data: { action: 'switch', customer: fixtures.E2E_VOICE_CUSTOMER, provider: 'elevenlabs', useDefaultVoice: true, confirm: true, version: view.providers.version }, headers: { Origin: origin } })
  expect([noId.status(), (await noId.json()).error]).toEqual([400, 'confirm_customer_mismatch'])
  const blocked = await page.request.post('/api/platform/voice-provider', { data: { action: 'switch', customer: fixtures.E2E_VOICE_CUSTOMER, confirmCustomer: fixtures.E2E_VOICE_CUSTOMER, provider: 'elevenlabs', useDefaultVoice: true, confirm: true, version: view.providers.version }, headers: { Origin: origin } })
  expect([blocked.status(), (await blocked.json()).error]).toEqual([409, 'blocked'])
  expect((await (await page.request.get(`/api/platform/voice-provider?customer=${fixtures.E2E_VOICE_CUSTOMER}`)).json()).providers.current).toBe('retell')
  await context.clearCookies()
  await useSession(context, fixtures.E2E_VOICE_SESSION_TOKEN)
  expect((await page.request.get('/api/platform/voice-provider')).status()).toBe(403)
  expect((await page.request.get(`/api/platform/voice-provider?customer=${fixtures.E2E_VOICE_CUSTOMER}`)).status()).toBe(403)
  expect((await page.request.post('/api/platform/voice-provider', { data: { action: 'check', customer: fixtures.E2E_VOICE_CUSTOMER, provider: 'retell' }, headers: { Origin: origin } })).status()).toBe(403)
})

test('admin: on a test business with evidence, Test now is offered, Review passes, Activate needs the business id typed back, the switch is audited; Roll back (typed) restores the previous provider', async ({ page, context }) => {
  const id = fixtures.E2E_VOICE_SWITCH_CUSTOMER
  await useSession(context, fixtures.E2E_ADMIN_SESSION_TOKEN)
  await page.goto(`/admin/voice-providers?customer=${id}`)
  const selected = page.locator('[data-vp-selected]')
  await expect(selected).toHaveAttribute('data-vp-selected', id)
  await expect(selected).toContainText('Switch Pools')
  await expect(selected).toContainText('Test business')
  await expect(selected).toContainText('OpenAI Realtime')
  await expect(selected).toContainText('Cedar')
  // History: the seeded finished admin test session on Retell counts as evidence; nothing said in it is shown.
  const history = page.locator('[data-vp-history]')
  await expect(history.locator('[data-vp-session="retell"]')).toHaveCount(1)
  await expect(history).toContainText('Admin test (customer path)')
  await expect(history).toContainText('Counts')
  await expect(page.locator('[data-vp-state="retell"]')).toContainText('Ready for production')
  await expect(page.locator('[data-vp-state="openai"]')).toContainText('Active for customers')
  const control = page.locator('[data-provider-control]')
  await control.getByRole('combobox', { name: 'Provider to switch to' }).selectOption('retell')
  await expect(control.locator('[data-test-now]')).toHaveAttribute('href', `/chat/${id}?test=retell`)
  await control.getByRole('combobox', { name: 'Replacement voice' }).selectOption('retell-Cimo')
  await control.getByRole('button', { name: 'Review checklist' }).click()
  const check = control.getByLabel('Switching checklist')
  await expect(check).toContainText('Verified for this business')
  await expect(check).not.toContainText('Blocked')
  await control.getByRole('button', { name: 'Activate…' }).click()
  const confirm = control.locator('[data-confirm-business]')
  await expect(confirm).toHaveAttribute('data-confirm-business', id)
  await expect(confirm).toContainText('Switch Pools')
  await expect(confirm).toContainText('Test business')
  const go = confirm.locator('[data-confirm-action]')
  await expect(go).toBeDisabled()
  await confirm.getByLabel('Type the business id to confirm').fill('e2e-voice')
  await expect(go).toBeDisabled()
  await confirm.getByLabel('Type the business id to confirm').fill(id)
  await expect(go).toBeEnabled()
  await go.click()
  await expect(control.getByRole('status')).toContainText('Activated Retell for Switch Pools')
  await expect(page.locator('[data-vp-state="retell"]')).toContainText('Active for customers')
  await expect(selected).toContainText('Cimo')
  const after = await (await page.request.get(`/api/platform/voice-provider?customer=${id}`)).json()
  expect([after.providers.current, after.voice.voiceName, after.providers.previous?.provider]).toEqual(['retell', 'Cimo', 'openai'])
  // Audited under the admin's own account; the other voice businesses are untouched.
  const detail = await (await page.request.get(`/api/platform/customer?id=${id}`)).json()
  expect(detail.audit.map((a) => a.action)).toContain('receptionist.provider_switched')
  expect((await (await page.request.get(`/api/platform/voice-provider?customer=${fixtures.E2E_VOICE_CUSTOMER}`)).json()).providers.current).toBe('retell')
  // Roll back, typed as well.
  await control.getByRole('button', { name: 'Roll back' }).click()
  const rb = control.locator('[data-confirm-business]')
  await expect(rb).toContainText('Roll back to openai')
  await rb.getByLabel('Type the business id to confirm').fill(id)
  await rb.locator('[data-confirm-action]').click()
  await expect(control.getByRole('status')).toContainText('Rolled back.')
  await expect(page.locator('[data-vp-state="openai"]')).toContainText('Active for customers')
  const restored = await (await page.request.get(`/api/platform/voice-provider?customer=${id}`)).json()
  expect([restored.providers.current, restored.voice.voiceName, restored.providers.previous]).toEqual(['openai', 'Cedar', null])
  await noSideScroll(page)
})
